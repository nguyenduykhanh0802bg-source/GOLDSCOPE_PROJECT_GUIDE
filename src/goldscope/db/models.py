"""Schema for migration 0001: sources, ingestion runs, raw objects, market/macro
observations and data-quality events (docs/DATABASE_DESIGN.md, migration plan step 1).

Decisions (ADR-0006):
- UUID primary keys generated by PostgreSQL (`gen_random_uuid()`).
- Price/value columns are unconstrained NUMERIC: precision/scale are chosen after the source
  audit (GS-001/002), never guessed here. Non-finite values are rejected by CHECK.
- Absolute instants are TIMESTAMPTZ (UTC); observation dates are DATE.
- No cascading deletes: referenced rows cannot be removed.
"""

from __future__ import annotations

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    Date,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    MetaData,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, TIMESTAMP, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, MappedColumn, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(constraint_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

AVAILABILITY_BASES = ("verified", "conservative_proxy", "first_seen", "unknown")
MAPPING_STATUSES = ("unverified", "verified", "deprecated")
RUN_STATUSES = ("running", "succeeded", "failed", "partial", "skipped")
SEVERITIES = ("info", "warning", "error", "critical")


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


def _finite(column: str) -> str:
    """Reject NaN/Infinity, which PostgreSQL NUMERIC accepts (and orders above all numbers)."""
    return f"{column} <> 'NaN' AND {column} <> 'Infinity' AND {column} <> '-Infinity'"


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {
        datetime: TIMESTAMP(timezone=True),
        dict[str, Any]: JSONB,
    }


def _uuid_pk() -> MappedColumn[uuid.UUID]:
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


_NOW = text("now()")


class DataSource(Base):
    """Provider metadata and policy. Changing a policy means a new policy_version row."""

    __tablename__ = "data_sources"
    __table_args__ = (
        UniqueConstraint(
            "provider", "dataset_key", "policy_version", name="provider_dataset_policy"
        ),
        CheckConstraint("provider <> '' AND dataset_key <> ''", name="keys_not_empty"),
        CheckConstraint("policy_version >= 1", name="policy_version_positive"),
        CheckConstraint(_in("mapping_status", MAPPING_STATUSES), name="mapping_status_valid"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    provider: Mapped[str] = mapped_column(String)
    dataset_key: Mapped[str] = mapped_column(String)
    policy_version: Mapped[int] = mapped_column(Integer, server_default="1")
    endpoint_key: Mapped[str | None] = mapped_column(String)
    mapping_status: Mapped[str] = mapped_column(String, server_default="unverified")
    time_policy: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))
    unit_policy: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))
    license_policy: Mapped[dict[str, Any]] = mapped_column(
        JSONB, server_default=text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = mapped_column(server_default=_NOW)


class IngestionRun(Base):
    __tablename__ = "ingestion_runs"
    __table_args__ = (
        CheckConstraint(_in("status", RUN_STATUSES), name="status_valid"),
        CheckConstraint("ended_at IS NULL OR ended_at >= started_at", name="ended_after_started"),
        CheckConstraint("(status = 'running') = (ended_at IS NULL)", name="running_iff_open"),
        CheckConstraint(
            "rows_fetched >= 0 AND rows_inserted >= 0 AND rows_rejected >= 0",
            name="counts_non_negative",
        ),
        Index("ix_ingestion_runs_source_started", "source_id", "started_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("data_sources.id"))
    started_at: Mapped[datetime]
    ended_at: Mapped[datetime | None]
    status: Mapped[str] = mapped_column(String, server_default="running")
    rows_fetched: Mapped[int] = mapped_column(Integer, server_default="0")
    rows_inserted: Mapped[int] = mapped_column(Integer, server_default="0")
    rows_rejected: Mapped[int] = mapped_column(Integer, server_default="0")
    error_code: Mapped[str | None] = mapped_column(String)
    error_message: Mapped[str | None] = mapped_column(Text)


class RawObject(Base):
    """Pointer + provenance for a stored raw response. Endpoint must not contain keys."""

    __tablename__ = "raw_objects"
    __table_args__ = (
        CheckConstraint("checksum_sha256 ~ '^[0-9a-f]{64}$'", name="checksum_sha256_hex"),
        CheckConstraint("size_bytes IS NULL OR size_bytes >= 0", name="size_non_negative"),
        Index("ix_raw_objects_checksum_sha256", "checksum_sha256"),
        Index("ix_raw_objects_run_id", "run_id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    run_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("ingestion_runs.id"))
    source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("data_sources.id"))
    endpoint: Mapped[str] = mapped_column(Text)
    fetched_at: Mapped[datetime]
    http_status: Mapped[int | None] = mapped_column(Integer)
    content_type: Mapped[str | None] = mapped_column(String)
    checksum_sha256: Mapped[str] = mapped_column(String(64))
    schema_version: Mapped[str | None] = mapped_column(String)
    storage_uri: Mapped[str] = mapped_column(Text)
    size_bytes: Mapped[int | None] = mapped_column(Integer)
    is_error: Mapped[bool] = mapped_column(server_default=text("false"))


class MarketObservation(Base):
    __tablename__ = "market_observations"
    __table_args__ = (
        UniqueConstraint(
            "asset_id", "source_id", "observation_date", "revision_key", name="business_key"
        ),
        CheckConstraint("asset_id <> ''", name="asset_not_empty"),
        CheckConstraint("revision_key <> ''", name="revision_key_not_empty"),
        CheckConstraint(f"price > 0 AND {_finite('price')}", name="price_positive_finite"),
        CheckConstraint(_in("availability_basis", AVAILABILITY_BASES), name="availability_valid"),
        CheckConstraint(
            "availability_basis = 'unknown' OR available_at IS NOT NULL",
            name="available_at_required",
        ),
        Index("ix_market_obs_asset_source_date", "asset_id", "source_id", "observation_date"),
        Index("ix_market_obs_available_at", "available_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    asset_id: Mapped[str] = mapped_column(String)
    source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("data_sources.id"))
    observation_date: Mapped[date] = mapped_column(Date)
    price: Mapped[Decimal] = mapped_column(Numeric)
    currency: Mapped[str] = mapped_column(String)
    unit: Mapped[str] = mapped_column(String)
    price_definition: Mapped[str] = mapped_column(String)
    revision_key: Mapped[str] = mapped_column(String)
    raw_object_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("raw_objects.id"))
    source_published_at: Mapped[datetime | None]
    available_at: Mapped[datetime | None]
    ingested_at: Mapped[datetime] = mapped_column(server_default=_NOW)
    vintage_date: Mapped[date | None] = mapped_column(Date)
    availability_basis: Mapped[str] = mapped_column(String, server_default="unknown")


class MacroSeries(Base):
    """Series metadata, versioned: units/frequency/release schedule changes add a new row."""

    __tablename__ = "macro_series"
    __table_args__ = (
        UniqueConstraint("series_id", "metadata_version", name="series_metadata_version"),
        CheckConstraint("series_id <> ''", name="series_not_empty"),
        CheckConstraint("metadata_version >= 1", name="metadata_version_positive"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    series_id: Mapped[str] = mapped_column(String)
    metadata_version: Mapped[int] = mapped_column(Integer, server_default="1")
    source_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("data_sources.id"))
    title: Mapped[str | None] = mapped_column(Text)
    units: Mapped[str | None] = mapped_column(String)
    frequency: Mapped[str | None] = mapped_column(String)
    release_schedule: Mapped[dict[str, Any]] = mapped_column(
        JSONB, server_default=text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = mapped_column(server_default=_NOW)


class MacroObservation(Base):
    """`value` is NULL for provider-missing points (never 0). Negative values are valid."""

    __tablename__ = "macro_observations"
    __table_args__ = (
        ForeignKeyConstraint(
            ["series_id", "metadata_version"],
            ["macro_series.series_id", "macro_series.metadata_version"],
            name="fk_macro_observations_series_macro_series",
        ),
        UniqueConstraint("series_id", "observation_date", "revision_key", name="business_key"),
        CheckConstraint("revision_key <> ''", name="revision_key_not_empty"),
        CheckConstraint(f"value IS NULL OR ({_finite('value')})", name="value_finite_or_null"),
        CheckConstraint(_in("availability_basis", AVAILABILITY_BASES), name="availability_valid"),
        CheckConstraint(
            "availability_basis = 'unknown' OR available_at IS NOT NULL",
            name="available_at_required",
        ),
        Index("ix_macro_obs_series_date", "series_id", "observation_date"),
        Index("ix_macro_obs_series_available_at", "series_id", "available_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    series_id: Mapped[str] = mapped_column(String)
    metadata_version: Mapped[int] = mapped_column(Integer)
    observation_date: Mapped[date] = mapped_column(Date)
    value: Mapped[Decimal | None] = mapped_column(Numeric)
    revision_key: Mapped[str] = mapped_column(String)
    raw_object_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("raw_objects.id"))
    source_published_at: Mapped[datetime | None]
    available_at: Mapped[datetime | None]
    ingested_at: Mapped[datetime] = mapped_column(server_default=_NOW)
    vintage_date: Mapped[date | None] = mapped_column(Date)
    availability_basis: Mapped[str] = mapped_column(String, server_default="unknown")


class DataQualityEvent(Base):
    __tablename__ = "data_quality_events"
    __table_args__ = (
        CheckConstraint(_in("severity", SEVERITIES), name="severity_valid"),
        CheckConstraint("affected_count >= 0", name="affected_count_non_negative"),
        CheckConstraint("rule <> ''", name="rule_not_empty"),
        Index("ix_data_quality_events_run_id", "run_id"),
        Index("ix_data_quality_events_created_at", "created_at"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    run_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("ingestion_runs.id"))
    rule: Mapped[str] = mapped_column(String)
    severity: Mapped[str] = mapped_column(String)
    affected_count: Mapped[int] = mapped_column(Integer, server_default="0")
    context: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))
    created_at: Mapped[datetime] = mapped_column(server_default=_NOW)
